const sections = rawData.split('\n\n');
const allFaqs = [];
const seenQs = new Set();

sections.forEach(section => {
    const lines = section.split('\n').filter(l => l.trim());
    lines.forEach(line => {
        const parts = line.split(',');
        if (parts.length < 3) return;
        
        const cat = parts[0].trim().replace(/\./g, '');
        const q = parts[1].trim();
        const a = parts[2].trim();
        
        if (q && a && !seenQs.has(q.toLowerCase())) {
            allFaqs.push({ category: cat, q: q, a: a });
            seenQs.add(q.toLowerCase());
        }
    });
});

process.stdout.write("const additionalFaqs = [\n");
allFaqs.forEach((faq, index) => {
    const comma = index === allFaqs.length - 1 ? "" : ",";
    process.stdout.write("  { q: \"" + faq.q + "\", a: \"" + faq.a + "\" }" + comma + " // " + faq.category + "\n");
});
process.stdout.write("];\n");
